const inrFormatter = new Intl.NumberFormat('en-IN', {
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
});

export function formatINR(value: number): string {
  const sign = value < 0 ? '-' : '';
  return `${sign}₹${inrFormatter.format(Math.abs(value))}`;
}

